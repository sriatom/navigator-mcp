# --------------------------------------------------------------------------- credential types
def test_credential_types():
    assert cr.infer_type({"USERNAME", "LOGIN_PASSWORD"}) == "LOGIN"
    assert cr.infer_type({"TOKEN"}) == "API_TOKEN"
    assert cr.infer_type({"COMMUNITY"}) == "SNMP"
    assert cr.infer_type({"AUTH_USER", "AUTH_PASS"}) == "SMTP"
    assert cr.missing_fields("LOGIN", {"USERNAME"}) == ("LOGIN_PASSWORD|PASSWORD",)
    assert cr.missing_fields("SNMP", {"USERNAME", "AUTH_PASS"}) == ()
    assert cr.missing_fields("CUSTOM", set()) == ()


async def test_credential_list_types(vault):
    (vault / "CREDENTIALS.yml").write_text(
        f"DATA:\n- {{TAG: TOK, TYPE: API_TOKEN, API_KEY: {SECRET}}}\n"
        f"- {{TAG: HALF, TYPE: LOGIN, USERNAME: someone}}\n")
    out = await text("credential_list")
    assert "TOK: type API_TOKEN; fields API_KEY" in out
    assert "HALF: type LOGIN; fields USERNAME; MISSING LOGIN_PASSWORD|PASSWORD" in out
    assert SECRET not in out and "someone" not in out


