# --------------------------------------------------------------------------- record types
def test_mixed_inventory_valid(cat):
    rep = inv.validate_text(MIXED, {"FAB"}, catalog=cat)
    assert rep.ok, rep.errors
    assert (len(rep.devices), len(rep.controllers), len(rep.oob)) == (2, 1, 1)
    assert "1 controller(s), 1 OOB" in rep.text("MIX")


def test_controller_and_oob_errors(cat):
    bad = """\
CONTROLLERS:
- {NAME: C1, URL: "https://user:pw@x.example", VENDOR: CISCO, PRODUCT: VMANAGE, CREDENTIAL: FAB, IS_ENABLED: true}
- {NAME: C1, URL: "ftp://x", VENDOR: CISCO, PRODUCT: WIDGETRON, CREDENTIAL: FAB, IS_ENABLED: true, MANAGES: [GHOST]}
OOB:
- {NAME: O1, ADDR: 10.0.0.1, TYPE: TOASTER, VENDOR: X, CREDENTIAL: FAB}
"""
    rep = inv.validate_text(bad, {"FAB"}, catalog=cat)
    errs = "\n".join(rep.errors)
    assert "must not contain a user name or password" in errs
    assert "URL must look like" in errs
    assert "duplicate NAME C1" in errs
    assert "TYPE must be one of" in errs
    assert "missing IS_ENABLED" in errs
    warns = "\n".join(rep.warnings)
    assert "WIDGETRON" in warns and "GHOST" in warns


def test_unknown_os_warns_with_catalog(cat):
    rep = inv.validate_text(MIXED.replace("OS: mikrotik_routeros", "OS: ZZOS"), {"FAB"}, catalog=cat)
    assert rep.ok
    assert any("ZZOS" in w and "platform catalogue" in w for w in rep.warnings)


