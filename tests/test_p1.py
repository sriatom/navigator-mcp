async def test_inventory_query_projection(mixed):
    r = await call("inventory_query", name="MIX", fields=["device_name", "PLATFORM", "READS", "SITE"])
    rows = result(r)
    assert rows[0] == {"DEVICE_NAME": "VE1", "PLATFORM": "VIPTELA", "READS": "native:vmanage", "SITE": "BR1"}
    assert rows[1]["PLATFORM"] == "ROUTEROS" and rows[1]["READS"] == "delegated:multivendor"
    r = await call("inventory_query", name="MIX", record_type="CONTROLLER")
    rows = result(r)
    assert rows == [{"NAME": "VMANAGE1", "URL": "https://10.9.0.10:8443", "VENDOR": "CISCO",
                     "PRODUCT": "VMANAGE", "CREDENTIAL": "FAB"}]
    with pytest.raises(ToolError, match="record_type"):
        await call("inventory_query", name="MIX", record_type="WIDGET")


async def test_inventory_query_masks_disallowed_tag(mixed):
    from conftest import write_boot
    write_boot(mixed.parent, """\
        CONSUMERS:
          LAB_BOT: {INVENTORIES: [INVENTORY_MIX], CREDENTIALS: [OTHER]}
        CONSUMER: LAB_BOT
        """)
    r = await call("inventory_query", name="MIX", fields=["DEVICE_NAME", "CREDENTIAL"])
    rows = result(r)
    assert {row["CREDENTIAL"] for row in rows} == {"(not allowed)"}


async def test_platform_tools(vault):
    out = await text("platform_list", vendor="cisco")
    assert "NXOS  CISCO  reads=delegated:pyats  writes=native:netmiko" in out
    out = await text("platform_list", adapter="multivendor")
    assert "VYOS" in out and not any(line.startswith("EOS ") for line in out.splitlines())
    r = await call("platform_show", platform="arista_eos")
    p = result(r)
    assert p["ID"] == "EOS" and p["COMMAND_CATEGORIES"] == ["bgp", "system"]
    r = await call("platform_show", platform="panorama")
    p = result(r)
    assert p["PRODUCT"] == "PANORAMA"
    with pytest.raises(ToolError, match="unknown platform"):
        await call("platform_show", platform="NOPE")


async def test_command_list(vault):
    out = await text("command_list", platform="EOS")
    assert out.startswith("EOS: 3 commands in 2 categories")
    out = await text("command_list", platform="ARISTA_EOS", category="BGP")
    assert "show ip bgp summary" in out
    with pytest.raises(ToolError, match="no command list for HP_COMWARE"):
        await call("command_list", platform="HP_COMWARE")
    with pytest.raises(ToolError, match="no category"):
        await call("command_list", platform="EOS", category="nope")
