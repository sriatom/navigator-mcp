"""Generate atlas_inventory/catalog/PLATFORMS.yml from netmiko's platform list + platforms_overlay.yml.
Platforms owned by a vendor pack (navigator_packs/*/pack.yml) are not written here: ATLAS merges the
enabled packs at runtime, and their netmiko names never become generic platforms.

Run with any python that has netmiko and PyYAML installed (ATLAS itself does not need netmiko):
    python scripts/gen_platforms.py            # writes the file
    python scripts/gen_platforms.py --check    # exit 1 if the committed file is out of date
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import navigator_packs  # noqa: E402

CATALOG = Path(__file__).resolve().parent.parent / "atlas_inventory" / "catalog"
OVERLAY = CATALOG / "platforms_overlay.yml"
OUT = CATALOG / "PLATFORMS.yml"

# netmiko device_types that are not separate platforms (transport variants and helpers).
SKIP_SUFFIXES = ("_telnet", "_serial", "_ssh")
SKIP = {"autodetect", "terminal_server", "generic", "generic_termserver", "generic_telnet"}


def netmiko_types() -> tuple[str, list[str]]:
    import netmiko
    from netmiko.ssh_dispatcher import CLASS_MAPPER_BASE
    types = sorted(t for t in CLASS_MAPPER_BASE
                   if t not in SKIP and not t.endswith(SKIP_SUFFIXES))
    return netmiko.__version__, types


def build() -> str:
    overlay = yaml.safe_load(OVERLAY.read_text())
    plats: dict = {k: dict(v) for k, v in overlay["PLATFORMS"].items()}
    version, types = netmiko_types()
    claimed = {p.get("netmiko") for p in plats.values()} | navigator_packs.claimed_netmiko_names()
    for p in plats.values():
        p.setdefault("aliases", [])
        p["source"] = "overlay"
    for t in types:
        if t in claimed:
            continue
        pid = t.upper()
        if pid in plats:
            continue
        gd = navigator_packs.pack("generic").get("generic_defaults") or {}
        plats[pid] = {"vendor": t.split("_")[0].upper(), "aliases": [], "netmiko": t,
                      "conn": list(gd.get("conn") or ["SSH"]), "reads": gd.get("reads", "native:generic-netmiko"),
                      "writes": gd.get("writes", "none"), "source": "netmiko"}
    head = (f"# GENERATED by scripts/gen_platforms.py from netmiko {version} + platforms_overlay.yml.\n"
            f"# Do not edit by hand. {len(plats)} platforms "
            f"({sum(1 for p in plats.values() if p['source'] == 'overlay')} from the overlay).\n")
    body = {"NETMIKO_VERSION": version,
            "PLATFORMS": dict(sorted(plats.items())),
            "CONTROLLER_PRODUCTS": overlay.get("CONTROLLER_PRODUCTS") or {},
            "OOB_TYPES": overlay.get("OOB_TYPES") or {},
            "COMMAND_KEYS": overlay.get("COMMAND_KEYS") or {}}
    return head + yaml.safe_dump(body, sort_keys=False, width=120)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        ok = OUT.is_file() and OUT.read_text() == text
        print("PLATFORMS.yml is up to date" if ok else "PLATFORMS.yml is OUT OF DATE: re-run gen_platforms.py")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
